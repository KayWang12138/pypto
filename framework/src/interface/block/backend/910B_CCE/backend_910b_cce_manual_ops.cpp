// Helper function to compute stride-based offset
// In single-file mode: compute strides from IR tensor shape (no Tensor struct available)
// In normal mode: use Tensor struct strides (same as backend_910b_cce_ops.cpp)
static std::string ComputeManualOffset(codegen::CCECodegen& codegen, const std::string& tensor_var_name,
                                       const ir::MakeTuplePtr& offsets,
                                       const ir::TensorTypePtr& tensor_type) {
  if (codegen.IsSingleFileMode()) {
    return codegen.ComputeIRBasedOffset(tensor_type, offsets);
  }
  // Normal mode: use Tensor struct strides
  std::string tensor_struct = codegen.GetTensorStruct(tensor_var_name);
  std::ostringstream offset_computation;
  offset_computation << "(" << tensor_struct << "->start_offset";
  for (size_t i = 0; i < offsets->elements_.size(); ++i) {
    offset_computation << " + " << codegen.GetExprAsCode(offsets->elements_[i]) << " * " << tensor_struct
                       << "->strides[" << i << "]";
  }
  offset_computation << ")";
  return offset_computation.str();
}

static bool IsNZTensorType(const ir::TensorTypePtr& tensor_type) {
  return tensor_type && tensor_type->tensor_view_.has_value() &&
         tensor_type->tensor_view_->layout == ir::TensorLayout::NZ;
}

static int64_t GetNZInnerCols(const DataType& dtype) {
  if (dtype == DataType::BOOL || dtype == DataType::INT8 || dtype == DataType::UINT8) {
    return 32;
  }
  if (dtype == DataType::FP16 || dtype == DataType::BF16 ||
      dtype == DataType::INT16 || dtype == DataType::UINT16) {
    return 16;
  }
  if (dtype == DataType::FP32 || dtype == DataType::INT32 || dtype == DataType::UINT32) {
    return 8;
  }
  if (dtype == DataType::INT64 || dtype == DataType::UINT64) {
    return 4;
  }
  throw pypto::ir::ValueError("CCE NZ store does not support destination dtype " + dtype.ToString());
}

static int64_t GetStaticConstIntOrThrow(const ir::ExprPtr& expr, const std::string& message) {
  auto value = ir::As<ir::ConstInt>(expr);
  if (!value) {
    throw pypto::ir::ValueError(message);
  }
  return value->value_;
}

static bool IsConstZero(const ir::ExprPtr& expr) {
  auto value = ir::As<ir::ConstInt>(expr);
  return value && value->value_ == 0;
}

static void ValidateCCEStoreNZPreconditions(const std::string& op_name,
                                            const ir::ExprPtr& src_expr,
                                            const ir::MakeTuplePtr& offsets,
                                            const ir::TensorTypePtr& dst_tensor_type) {
  if (!IsNZTensorType(dst_tensor_type)) {
    return;
  }

  auto src_tile_type = ir::As<ir::TileType>(src_expr->GetType());
  CHECK(src_tile_type != nullptr) << op_name << ": source must be TileType";
  CHECK(src_tile_type->memref_.has_value()) << op_name << ": source tile must have an allocated memory space";
  if (src_tile_type->memref_.value()->memory_space_ != ir::MemorySpace::Acc) {
    throw pypto::ir::ValueError(op_name + ": CCE NZ output currently only supports Acc source tiles");
  }

  if (dst_tensor_type->shape_.size() != 2) {
    throw pypto::ir::ValueError(op_name + ": CCE NZ output currently requires a 2D destination tensor");
  }
  if (offsets->elements_.size() != 2 || !IsConstZero(offsets->elements_[0]) || !IsConstZero(offsets->elements_[1])) {
    throw pypto::ir::ValueError(op_name + ": CCE NZ output currently requires offsets=[0, 0]");
  }

  const int64_t rows = GetStaticConstIntOrThrow(
      dst_tensor_type->shape_[0], op_name + ": CCE NZ output currently requires a static destination row shape");
  const int64_t cols = GetStaticConstIntOrThrow(
      dst_tensor_type->shape_[1], op_name + ": CCE NZ output currently requires a static destination column shape");
  const int64_t c0 = GetNZInnerCols(dst_tensor_type->dtype_);
  if (rows % 16 != 0 || cols % c0 != 0) {
    throw pypto::ir::ValueError(
        op_name + ": CCE NZ output requires rows divisible by 16 and cols divisible by the destination C0 size");
  }
}

// ============================================================================
// manual.load �?args = [tensor, offsets, out_tile]
// Emits: TASSIGN(tensor_global, ptr + offset); TLOAD(out_tile, tensor_global);
// ============================================================================
static std::string MakeManualLoadCodegenCCE(const ir::CallPtr& op, codegen::CodegenBase& codegen_base) {
  auto& codegen = dynamic_cast<codegen::CCECodegen&>(codegen_base);
  CHECK(op->args_.size() == 3) << "manual.load requires 3 arguments: tensor, offsets, out_tile";

  auto src_tensor_var_ptr = std::dynamic_pointer_cast<const ir::Var>(op->args_[0]);
  CHECK(src_tensor_var_ptr != nullptr) << "manual.load source tensor must be a Var";

  auto offsets_tuple = std::dynamic_pointer_cast<const ir::MakeTuple>(op->args_[1]);
  CHECK(offsets_tuple != nullptr) << "manual.load second argument must be a tuple (offsets)";

  auto out_tile = std::dynamic_pointer_cast<const ir::Var>(op->args_[2]);
  if (!out_tile) {
    // Support TupleGetItemExpr (e.g., qk_vec_buf[0]) �?resolved by GetExprAsCode below
    CHECK(ir::As<ir::TileType>(op->args_[2]->GetType()) != nullptr)
        << "manual.load third argument (out) must be a tile (Var or TupleGetItemExpr)";
  }

  std::string src_tensor_var = codegen.GetVarName(src_tensor_var_ptr);
  auto src_tensor_type = std::dynamic_pointer_cast<const ir::TensorType>(src_tensor_var_ptr->GetType());
  CHECK(src_tensor_type != nullptr) << "manual.load source must be TensorType";

  std::string offset = ComputeManualOffset(codegen, src_tensor_var, offsets_tuple, src_tensor_type);
  std::string src_ptr = codegen.GetPointer(src_tensor_var);
  std::string out_name = codegen.GetExprAsCode(op->args_[2]);

  codegen.Emit("TASSIGN(" + src_tensor_var + ", " + src_ptr + " + " + offset + ");");
  codegen.Emit("TLOAD(" + out_name + ", " + src_tensor_var + ");");
  return "";
}

// ============================================================================
// manual.store �?args = [tile, offsets, output_tensor]
// Emits: TASSIGN(tensor_global, ptr + offset); TSTORE(tensor_global, tile);
// ============================================================================
static std::string MakeManualStoreCodegenCCE(const ir::CallPtr& op, codegen::CodegenBase& codegen_base) {
  auto& codegen = dynamic_cast<codegen::CCECodegen&>(codegen_base);
  CHECK(op->args_.size() == 3) << "manual.store requires 3 arguments: tile, offsets, output_tensor";

  std::string src_tile = codegen.GetExprAsCode(op->args_[0]);

  auto offsets_tuple = std::dynamic_pointer_cast<const ir::MakeTuple>(op->args_[1]);
  CHECK(offsets_tuple != nullptr) << "manual.store second argument must be a tuple (offsets)";

  auto dst_tensor_var_ptr = std::dynamic_pointer_cast<const ir::Var>(op->args_[2]);
  CHECK(dst_tensor_var_ptr != nullptr) << "manual.store destination tensor must be a Var";

  std::string dst_tensor_var = codegen.GetVarName(dst_tensor_var_ptr);
  auto dst_tensor_type = std::dynamic_pointer_cast<const ir::TensorType>(dst_tensor_var_ptr->GetType());
  CHECK(dst_tensor_type != nullptr) << "manual.store destination must be TensorType";
  ValidateCCEStoreNZPreconditions("manual.store", op->args_[0], offsets_tuple, dst_tensor_type);

  std::string offset = ComputeManualOffset(codegen, dst_tensor_var, offsets_tuple, dst_tensor_type);
  std::string dst_ptr = codegen.GetPointer(dst_tensor_var);

  codegen.Emit("TASSIGN(" + dst_tensor_var + ", " + dst_ptr + " + " + offset + ");");

  // Build template parameters: TSTORE<TileData, GlobalData, AtomicType, ReluPreMode>(dst, src, ...)
  // Per pto-isa: template order is <TileData, GlobalData, AtomicType, ReluPreMode>
  // Function arg order is (GlobalData& dst, TileData& src, ...)
  std::string relu_template;

  if (op->HasKwarg("relu_pre_mode")) {
    const std::string& relu_str = op->GetKwarg<std::string>("relu_pre_mode");
    std::string relu_enum;
    if (relu_str == "no_relu") {
      relu_enum = "ReluPreMode::NoRelu";
    } else if (relu_str == "normal_relu") {
      relu_enum = "ReluPreMode::NormalRelu";
    } else {
      throw pypto::ir::ValueError("Invalid relu_pre_mode: " + relu_str);
    }
    relu_template = relu_enum;
  }

  // Build function arguments
  std::string args = dst_tensor_var + ", " + src_tile;

  if (op->HasKwarg("pre_quant_scalar")) {
    int pre_quant = op->GetKwarg<int>("pre_quant_scalar");
    args += ", " + std::to_string(pre_quant);
  }

  // Emit TSTORE
  if (!relu_template.empty()) {
    // TSTORE<TileData, GlobalData, AtomicType::AtomicNone, ReluPreMode>(dst, src[, preQuant])
    std::string src_type = TileTypeStringForTemplate(codegen, src_tile, op->args_[0]);
    codegen.Emit("TSTORE<" + src_type + ", decltype(" + dst_tensor_var + "), AtomicType::AtomicNone, " + relu_template + ">(" + args + ");");
  } else if (op->HasKwarg("pre_quant_scalar")) {
    // TSTORE<TileData, GlobalData>(dst, src, preQuant) — default AtomicType & ReluPreMode
    std::string src_type = TileTypeStringForTemplate(codegen, src_tile, op->args_[0]);
    codegen.Emit("TSTORE<" + src_type + ", decltype(" + dst_tensor_var + ")>(" + args + ");");
  } else {
    codegen.Emit("TSTORE(" + args + ");");
  }
  return "";
}

// ============================================================================
// manual.store_fp �?args = [tile, fp_tile, offsets, output_tensor]
// Emits: TASSIGN(tensor_global, ptr + offset); TSTORE_FP(tensor_global, tile, fp_tile);
// ============================================================================
static std::string MakeManualStoreFpCodegenCCE(const ir::CallPtr& op, codegen::CodegenBase& codegen_base) {
  auto& codegen = dynamic_cast<codegen::CCECodegen&>(codegen_base);
  CHECK(op->args_.size() == 4)
      << "manual.store_fp requires 4 arguments: tile, fp_tile, offsets, output_tensor";

  auto src_tile_type = ir::As<ir::TileType>(op->args_[0]->GetType());
  CHECK(src_tile_type != nullptr) << "manual.store_fp source must be TileType";
  CHECK(src_tile_type->memref_.has_value())
      << "manual.store_fp source tile must have an allocated memory space";
  if (src_tile_type->memref_.value()->memory_space_ != ir::MemorySpace::Acc) {
    throw pypto::ir::ValueError("manual.store_fp: source tile must be allocated in Acc memory");
  }

  auto fp_tile_type = ir::As<ir::TileType>(op->args_[1]->GetType());
  CHECK(fp_tile_type != nullptr) << "manual.store_fp fp tile must be TileType";
  CHECK(fp_tile_type->memref_.has_value())
      << "manual.store_fp fp tile must have an allocated memory space";
  if (fp_tile_type->memref_.value()->memory_space_ != ir::MemorySpace::Scaling) {
    throw pypto::ir::ValueError("manual.store_fp: fp tile must be allocated in Scaling memory");
  }

  auto offsets_tuple = std::dynamic_pointer_cast<const ir::MakeTuple>(op->args_[2]);
  CHECK(offsets_tuple != nullptr) << "manual.store_fp third argument must be a tuple (offsets)";

  auto dst_tensor_var_ptr = std::dynamic_pointer_cast<const ir::Var>(op->args_[3]);
  CHECK(dst_tensor_var_ptr != nullptr) << "manual.store_fp destination tensor must be a Var";

  std::string dst_tensor_var = codegen.GetVarName(dst_tensor_var_ptr);
  auto dst_tensor_type = std::dynamic_pointer_cast<const ir::TensorType>(dst_tensor_var_ptr->GetType());
  CHECK(dst_tensor_type != nullptr) << "manual.store_fp destination must be TensorType";
  ValidateCCEStoreNZPreconditions("manual.store_fp", op->args_[0], offsets_tuple, dst_tensor_type);

  std::string offset = ComputeManualOffset(codegen, dst_tensor_var, offsets_tuple, dst_tensor_type);
  std::string dst_ptr = codegen.GetPointer(dst_tensor_var);
  std::string src_tile = codegen.GetExprAsCode(op->args_[0]);
  std::string fp_tile = codegen.GetExprAsCode(op->args_[1]);

  codegen.Emit("TASSIGN(" + dst_tensor_var + ", " + dst_ptr + " + " + offset + ");");
  codegen.Emit("TSTORE_FP(" + dst_tensor_var + ", " + src_tile + ", " + fp_tile + ");");
  return "";
}

