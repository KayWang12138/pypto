// ============================================================================
// manual.insert �?args = [src, index_row, index_col, dst] or [src, index_row, index_col, offset, dst]
// Emits TINSERT(dst, src, indexRow, indexCol);
// With offset: Emits TASSIGN(dst, base + offset); TINSERT(...); TASSIGN(dst, base);
// ============================================================================
static std::string MakeManualInsertCodegenCCE(const ir::CallPtr& op, codegen::CodegenBase& codegen_base) {
  auto& codegen = dynamic_cast<codegen::CCECodegen&>(codegen_base);
  CHECK(op->args_.size() == 4 || op->args_.size() == 5)
      << "manual.insert: expected 4 or 5 args, got " << op->args_.size();

  bool has_offset = (op->args_.size() == 5);
  std::string src = codegen.GetExprAsCode(op->args_[0]);
  std::string index_row = codegen.GetExprAsCode(op->args_[1]);
  std::string index_col = codegen.GetExprAsCode(op->args_[2]);
  std::string dst, offset, base_addr;

  if (has_offset) {
    offset = codegen.GetExprAsCode(op->args_[3]);
    dst = codegen.GetExprAsCode(op->args_[4]);
    // For array-subscript dst (e.g. NBuffer auto-rotate ``arr[ctx.cursor%2]``),
    // tile_addresses_ does not have an entry — use the runtime ``data()``
    // method to get the actual base address. Save it to a temp because
    // TASSIGN mutates ``dst.data()``; the second TASSIGN (restore) needs
    // the original address.
    if (dst.find('[') != std::string::npos) {
      static int insert_addr_counter = 0;
      std::string addr_tmp = "_tinsert_addr_" + std::to_string(insert_addr_counter++);
      codegen.Emit("uint64_t " + addr_tmp + " = (uint64_t)(" + dst + ".data());");
      base_addr = addr_tmp;
    } else {
      base_addr = codegen.GetTileAddress(dst);
    }
    codegen.Emit("TASSIGN(" + dst + ", " + base_addr + " + " + offset + ");");
  } else {
    dst = codegen.GetExprAsCode(op->args_[3]);
  }

  codegen.Emit("TINSERT(" + dst + ", " + src + ", " + index_row + ", " + index_col + ");");

  if (has_offset) {
    codegen.Emit("TASSIGN(" + dst + ", " + base_addr + ");");
  }

  return "";
}

// ============================================================================
// manual.move �?args = [src, dst]
// Emits TMOV(dst, src);
// ============================================================================
static std::string MakeManualMoveCodegenCCE(const ir::CallPtr& op, codegen::CodegenBase& codegen_base) {
  auto& codegen = dynamic_cast<codegen::CCECodegen&>(codegen_base);
  CHECK(op->args_.size() == 2)
      << "manual.move: expected 2 args, got " << op->args_.size();

  std::string src = codegen.GetExprAsCode(op->args_[0]);
  std::string dst = codegen.GetExprAsCode(op->args_[1]);

  // Build template parameters
  std::string template_params = "";

  if (op->HasKwarg("acc_to_vec_mode")) {
    const std::string& mode_str = op->GetKwarg<std::string>("acc_to_vec_mode");
    std::string mode_enum;
    if (mode_str == "single_vec0") {
      mode_enum = "AccToVecMode::SingleModeVec0";
    } else if (mode_str == "single_vec1") {
      mode_enum = "AccToVecMode::SingleModeVec1";
    } else if (mode_str == "dual_split_m") {
      mode_enum = "AccToVecMode::DualModeSplitM";
    } else if (mode_str == "dual_split_n") {
      mode_enum = "AccToVecMode::DualModeSplitN";
    } else {
      throw pypto::ir::ValueError("Invalid acc_to_vec_mode: " + mode_str);
    }
    template_params = ", " + mode_enum;
  }

  if (op->HasKwarg("relu_pre_mode")) {
    const std::string& relu_str = op->GetKwarg<std::string>("relu_pre_mode");
    std::string relu_enum;
    if (relu_str == "no_relu") {
      relu_enum = "ReluPreMode::NoRelu";
    } else if (relu_str == "normal_relu") {
      relu_enum = "ReluPreMode::NormalRelu";
    } else {
      throw pypto::ir::ValueError("Invalid relu_pre_mode: " + relu_str);
    }
    template_params += ", " + relu_enum;
  }

  // Build function arguments
  std::string args = dst + ", " + src;

  if (op->HasKwarg("pre_quant_scalar")) {
    int pre_quant = op->GetKwarg<int>("pre_quant_scalar");
    args += ", " + std::to_string(pre_quant);
  }

  // Emit TMOV
  if (!template_params.empty()) {
    // decltype(arr[idx]) is not supported by bisheng — use the tile's concrete C++ Tile<...> type.
    std::string dst_type = TileTypeStringForTemplate(codegen, dst, op->args_[1]);
    std::string src_type = TileTypeStringForTemplate(codegen, src, op->args_[0]);
    codegen.Emit("TMOV<" + dst_type + ", " + src_type + template_params + ">(" + args + ");");
  } else {
    codegen.Emit("TMOV(" + args + ");");
  }

  return "";
}

// ============================================================================
// manual.move_fp �?args = [src, fp_tile, dst]
// Emits TMOV_FP(dst, src, fp) or TMOV<..., FpTileData, AccToVecMode, ReluPreMode>(dst, src, fp);
// ============================================================================
static std::string MakeManualMoveFpCodegenCCE(const ir::CallPtr& op, codegen::CodegenBase& codegen_base) {
  auto& codegen = dynamic_cast<codegen::CCECodegen&>(codegen_base);
  CHECK(op->args_.size() == 3)
      << "manual.move_fp: expected 3 args, got " << op->args_.size();

  auto src_tile_type = ir::As<ir::TileType>(op->args_[0]->GetType());
  CHECK(src_tile_type != nullptr) << "manual.move_fp source must be TileType";
  CHECK(src_tile_type->memref_.has_value())
      << "manual.move_fp source tile must have an allocated memory space";
  if (src_tile_type->memref_.value()->memory_space_ != ir::MemorySpace::Acc) {
    throw pypto::ir::ValueError("manual.move_fp: source tile must be allocated in Acc memory");
  }

  auto fp_tile_type = ir::As<ir::TileType>(op->args_[1]->GetType());
  CHECK(fp_tile_type != nullptr) << "manual.move_fp fp tile must be TileType";
  CHECK(fp_tile_type->memref_.has_value())
      << "manual.move_fp fp tile must have an allocated memory space";
  if (fp_tile_type->memref_.value()->memory_space_ != ir::MemorySpace::Scaling) {
    throw pypto::ir::ValueError("manual.move_fp: fp tile must be allocated in Scaling memory");
  }

  auto dst_tile_type = ir::As<ir::TileType>(op->args_[2]->GetType());
  CHECK(dst_tile_type != nullptr) << "manual.move_fp destination must be TileType";
  CHECK(dst_tile_type->memref_.has_value())
      << "manual.move_fp destination tile must have an allocated memory space";
  if (dst_tile_type->memref_.value()->memory_space_ != ir::MemorySpace::Vec) {
    throw pypto::ir::ValueError("manual.move_fp: destination tile must be allocated in Vec memory");
  }

  std::string src = codegen.GetExprAsCode(op->args_[0]);
  std::string fp_tile = codegen.GetExprAsCode(op->args_[1]);
  std::string dst = codegen.GetExprAsCode(op->args_[2]);
  std::string args = dst + ", " + src + ", " + fp_tile;

  std::string relu_template;
  if (op->HasKwarg("relu_pre_mode")) {
    const std::string& relu_str = op->GetKwarg<std::string>("relu_pre_mode");
    if (relu_str == "no_relu") {
      relu_template = "ReluPreMode::NoRelu";
    } else if (relu_str == "normal_relu") {
      relu_template = "ReluPreMode::NormalRelu";
    } else {
      throw pypto::ir::ValueError("Invalid relu_pre_mode: " + relu_str);
    }
  }

  if (op->HasKwarg("acc_to_vec_mode")) {
    const std::string& mode_str = op->GetKwarg<std::string>("acc_to_vec_mode");
    std::string mode_enum;
    if (mode_str == "single_vec0") {
      mode_enum = "AccToVecMode::SingleModeVec0";
    } else if (mode_str == "single_vec1") {
      mode_enum = "AccToVecMode::SingleModeVec1";
    } else if (mode_str == "dual_split_m" || mode_str == "dual_split_n") {
      throw pypto::ir::ValueError("manual.move_fp: fp_tile only supports single-mode acc_to_vec_mode");
    } else {
      throw pypto::ir::ValueError("Invalid acc_to_vec_mode: " + mode_str);
    }

    std::string fp_type = TileTypeStringForTemplate(codegen, fp_tile, op->args_[1]);
    std::string template_params = ", " + fp_type + ", " + mode_enum;
    if (!relu_template.empty()) {
      template_params += ", " + relu_template;
    }
    std::string dst_type = TileTypeStringForTemplate(codegen, dst, op->args_[2]);
    std::string src_type = TileTypeStringForTemplate(codegen, src, op->args_[0]);
    codegen.Emit("TMOV<" + dst_type + ", " + src_type + template_params + ">(" + args + ");");
    return "";
  }

  if (!relu_template.empty()) {
    std::string dst_type = TileTypeStringForTemplate(codegen, dst, op->args_[2]);
    std::string src_type = TileTypeStringForTemplate(codegen, src, op->args_[0]);
    std::string fp_type = TileTypeStringForTemplate(codegen, fp_tile, op->args_[1]);
    codegen.Emit("TMOV_FP<" + dst_type + ", " + src_type + ", " + fp_type + ", " +
                 relu_template + ">(" + args + ");");
  } else {
    codegen.Emit("TMOV_FP(" + args + ");");
  }

  return "";
}

