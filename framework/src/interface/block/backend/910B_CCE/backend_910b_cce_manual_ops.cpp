// manual.cast �?args = [src, dst] + mode kwarg
static std::string MakeManualCastCodegenCCE(const ir::CallPtr& op, codegen::CodegenBase& codegen_base) {
  auto& codegen = dynamic_cast<codegen::CCECodegen&>(codegen_base);
  CHECK(op->args_.size() == 2) << "manual.cast: expected 2 args (src, dst), got " << op->args_.size();
  std::string src = codegen.GetExprAsCode(op->args_[0]);
  std::string dst = codegen.GetExprAsCode(op->args_[1]);

  // Get round mode from kwargs �?manual.cast uses a string mode
  const std::string& mode_str = op->GetKwarg<std::string>("mode");
  static const std::vector<std::string> kModeNames = {"none", "rint",  "round", "floor",
                                                       "ceil", "trunc", "odd",   "cast_rint"};
  int mode_idx = -1;
  for (int i = 0; i < static_cast<int>(kModeNames.size()); ++i) {
    if (kModeNames[i] == mode_str) {
      mode_idx = i;
      break;
    }
  }
  CHECK(mode_idx >= 0) << "manual.cast: unknown round mode '" << mode_str << "'";

  codegen.Emit("TCVT(" + dst + ", " + src + ", " +
               codegen.GetTypeConverter().ConvertCastRoundMode(mode_idx) + ");");
  return "";
}

// manual.full/expands �?args = [scalar, dst]
static std::string MakeManualExpandsCodegenCCE(const ir::CallPtr& op, codegen::CodegenBase& codegen_base) {
  auto& codegen = dynamic_cast<codegen::CCECodegen&>(codegen_base);
  CHECK(op->args_.size() == 2) << "manual.full/expands: expected 2 args (scalar, dst), got "
                               << op->args_.size();
  std::string scalar = codegen.GetExprAsCode(op->args_[0]);
  std::string dst = codegen.GetExprAsCode(op->args_[1]);

  // aicore does not allow implicit cast from integer (including index) to float.
  // Insert explicit (float) cast when scalar is integer/index and dst element type is float.
  auto scalar_type = ir::As<ir::ScalarType>(op->args_[0]->GetType());
  auto tile_type   = ir::As<ir::TileType>(op->args_[1]->GetType());
  if (scalar_type && tile_type) {
    bool src_is_int = (scalar_type->dtype_ == DataType::INDEX  ||
                       scalar_type->dtype_ == DataType::INT8   ||
                       scalar_type->dtype_ == DataType::INT16  ||
                       scalar_type->dtype_ == DataType::INT32  ||
                       scalar_type->dtype_ == DataType::INT64  ||
                       scalar_type->dtype_ == DataType::UINT8  ||
                       scalar_type->dtype_ == DataType::UINT16 ||
                       scalar_type->dtype_ == DataType::UINT32 ||
                       scalar_type->dtype_ == DataType::UINT64);
    bool dst_is_float = (tile_type->dtype_ == DataType::FP16  ||
                         tile_type->dtype_ == DataType::FP32  ||
                         tile_type->dtype_ == DataType::BF16);
    if (src_is_int && dst_is_float) {
      // aicore forbids direct unsigned→float cast; go via int64_t first.
      scalar = "(float)((int64_t)(" + scalar + "))";
    }
  }

  codegen.Emit("TEXPANDS(" + dst + ", " + scalar + ");");
  return "";
}

static bool NeedsNullPadSourceAliasCCE(const ir::TileTypePtr& tile_type) {
  return tile_type != nullptr && tile_type->tile_view_.has_value() &&
         tile_type->tile_view_.value().pad != ir::TilePad::null;
}

static std::pair<int64_t, int64_t> GetTileRowsCols(const ir::TileTypePtr& tile_type) {
  CHECK(tile_type != nullptr) << "manual.fillpad-like: expected TileType source";
  CHECK(tile_type->shape_.size() == 2)
      << "manual.fillpad-like: expected rank-2 tile, got " << tile_type->shape_.size();

  auto rows = ir::As<ir::ConstInt>(tile_type->shape_[0]);
  auto cols = ir::As<ir::ConstInt>(tile_type->shape_[1]);
  CHECK(rows != nullptr && cols != nullptr) << "manual.fillpad-like: expected static tile rows/cols";
  return {rows->value_, cols->value_};
}

static std::string BuildNullPadSourceAliasCCE(codegen::CCECodegen& codegen,
                                              const ir::TileTypePtr& src_tile_type,
                                              const std::string& src_name) {
  CHECK(src_tile_type != nullptr) << "manual.fillpad-like: expected TileType source";
  CHECK(src_tile_type->tile_view_.has_value()) << "manual.fillpad-like: expected source tile_view";

  auto [rows, cols] = GetTileRowsCols(src_tile_type);
  auto alias_tile_view = src_tile_type->tile_view_.value();
  alias_tile_view.pad = ir::TilePad::null;
  auto alias_tile_type = std::make_shared<ir::TileType>(
      src_tile_type->shape_, src_tile_type->dtype_, src_tile_type->memref_, alias_tile_view);

  std::string alias_tile_type_str = codegen.GetTypeConverter().ConvertTileType(alias_tile_type, rows, cols);
  static size_t fillpad_alias_counter = 0;
  std::string alias_suffix = std::to_string(fillpad_alias_counter++);
  std::string alias_type_name = "__manual_fillpad_src_alias_type_" + alias_suffix;
  std::string alias_name = "__manual_fillpad_src_alias_" + alias_suffix;

  codegen.Emit("using " + alias_type_name + " = " + alias_tile_type_str + ";");
  codegen.Emit(alias_type_name + " " + alias_name + "(" + src_name + ".GetValidRow(), " +
               src_name + ".GetValidCol());");
  codegen.Emit("TASSIGN(" + alias_name + ", " + codegen.GetTileAddress(src_name) + ");");
  return alias_name;
}

